"""Feed reads (docs/M3-DESIGN.md §3.4 #1, #2, #10, #11, #12; §3.4b #7).

Lists are keyset-paginated (D40). The cursor always comes from the last *row read*, before the
live deed check of composition drops anything, so pages never skip or repeat. Rows are read with
``populate_existing`` because ``listed`` is generated by the database.
"""

