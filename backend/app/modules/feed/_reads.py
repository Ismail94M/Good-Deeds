# Interim copy from the design (§6.3 "Report comment").
COMMENT_REPORT_LABELS: dict[CommentReportReason, str] = {
    CommentReportReason.THREAT_OR_HARASSMENT: "Threatening or harassing",
    CommentReportReason.HATE: "Hateful",
    CommentReportReason.PERSONAL_INFO: "Shares someone's personal information",
    CommentReportReason.SPAM: "Spam or scam",
    CommentReportReason.OTHER: "Something else",
}


class Unprocessable(AppError):
    status_code = 422


def deed_unavailable() -> NotFound:
    """The public page's single answer for missing, hidden, withdrawn, removed and never-existing
    deeds (identical body)."""
    return NotFound("This deed isn't available.", code="deed_unavailable")


def user_not_found() -> NotFound:
    return NotFound("We couldn't find that person.", code="user_not_found")


def _newest_first(stmt: Any, cursor: str | None, limit: int) -> Any:
    if cursor is not None:
        at, last_id = _cursor.decode(cursor)
        stmt = stmt.where(tuple_(FeedPost.published_at, FeedPost.deed_id) < tuple_(at, last_id))
    return (
        stmt.order_by(FeedPost.published_at.desc(), FeedPost.deed_id.desc())
        .limit(limit + 1)
        .execution_options(populate_existing=True)
    )


async def _post_page(
    session: AsyncSession,
    stmt: Any,
    viewer_id: uuid.UUID,
    storage: ObjectStorage,
    cursor: str | None,
    limit: int,
) -> PostPage:
    rows = list(await session.scalars(_newest_first(stmt, cursor, limit)))
    page, more = rows[:limit], len(rows) > limit
    return PostPage(
        items=await _compose.compose(session, page, viewer_id, storage),
        next_cursor=_cursor.encode(page[-1].published_at, page[-1].deed_id) if more else None,
    )


# --------------------------------------------------- #1 the feed


async def _top_page(
    session: AsyncSession,
    period: TopPeriod,
    viewer_id: uuid.UUID,
    storage: ObjectStorage,
    cursor: str | None,
    limit: int,
) -> PostPage:
    after = 0
    snapshot: FeedTopSnapshot | None
    if cursor is not None:
        snapshot_id, after = _cursor.decode_top(cursor, period.value)
        snapshot = await session.get(FeedTopSnapshot, snapshot_id)
        # Pruned (more than two refreshes ago) or another period's snapshot.
        if snapshot is None or snapshot.period != period:
            raise _cursor.invalid_cursor()
    else:
        snapshot = await _top.newest_snapshot(session, period)
        if snapshot is None:
            return PostPage(items=[], next_cursor=None)
    # Entries whose post is no longer listed are skipped here (hidden or withdrawn at once).
    rows = list(
        (
            await session.execute(
                select(FeedTopEntry.rank, FeedPost)
                .join(FeedPost, FeedPost.deed_id == FeedTopEntry.deed_id)
                .where(
                    FeedTopEntry.snapshot_id == snapshot.id,
                    FeedTopEntry.rank > after,
                    FeedPost.listed,
                )
                .order_by(FeedTopEntry.rank)
                .limit(limit + 1)
                .execution_options(populate_existing=True)
            )
        ).all()
    )
    page, more = rows[:limit], len(rows) > limit
    ranks = {post.deed_id: rank for rank, post in page}
    return PostPage(
        items=await _compose.compose(
            session, [post for _, post in page], viewer_id, storage, ranks=ranks
        ),
        next_cursor=_cursor.encode_top(period.value, snapshot.id, page[-1][0]) if more else None,
    )


async def feed(
    session: AsyncSession,
    viewer_id: uuid.UUID,
    storage: ObjectStorage,
    *,
    tab: Tab,
    period: TopPeriod | None = None,
    cursor: str | None = None,
    limit: int = _cursor.DEFAULT_PAGE_SIZE,
) -> PostPage:
    """Nearby (all of Bangalore, newest first), Following (deeds whose doer **or** reporter the
    caller follows, Q25), or Top for a period (default week, Q26)."""
    if tab != "top" and period is not None:
        raise Unprocessable("A period only goes with the Top tab.", code="invalid_period")
    if tab == "top":
        return await _top_page(session, period or TopPeriod.WEEK, viewer_id, storage, cursor, limit)
    stmt = select(FeedPost).where(FeedPost.listed)
    if tab == "following":
        followed = select(Follow.followed_id).where(Follow.follower_id == viewer_id)
        stmt = stmt.where(or_(FeedPost.doer_id.in_(followed), FeedPost.reporter_id.in_(followed)))
    return await _post_page(session, stmt, viewer_id, storage, cursor, limit)


# --------------------------------------------------- #2 deed page, #10 public page


async def deed_detail(
    session: AsyncSession, deed_id: uuid.UUID, viewer_id: uuid.UUID, storage: ObjectStorage
) -> PostDetail:
    found = await _access.viewable(session, deed_id, viewer_id)
    out = await _compose.detail(session, found, viewer_id, storage)
    if out is None:
        raise _access.deed_not_found()
    return out


async def public_deed(
    session: AsyncSession, deed_id: uuid.UUID, storage: ObjectStorage
) -> PublicDeed:
    found = await _access.access(session, deed_id, None)
    if found is None or not found.public:
        raise deed_unavailable()
    out = await _compose.public(session, found, storage)
    if out is None:
        raise deed_unavailable()
    return out


# --------------------------------------------------- #11 profiles


async def active_user(session: AsyncSession, handle: str) -> uuid.UUID:
    user = await identity.get_user_by_handle(session, handle)
    if user is None or not await identity.is_active(session, user.id):
        raise user_not_found()
    return user.id


async def user_deeds(
    session: AsyncSession,
    handle: str,
    viewer_id: uuid.UUID,
    storage: ObjectStorage,
    *,
    cursor: str | None = None,
    limit: int = _cursor.DEFAULT_PAGE_SIZE,
) -> PostPage:
    """Listed deeds where the person is the doer, newest first."""
    user_id = await active_user(session, handle)
    stmt = select(FeedPost).where(FeedPost.listed, FeedPost.doer_id == user_id)
    return await _post_page(session, stmt, viewer_id, storage, cursor, limit)


async def social(session: AsyncSession, handle: str, viewer_id: uuid.UUID | None) -> SocialOut:
    """Follower and following counts (counts only, Q36); ``is_following`` when signed in."""
    user_id = await active_user(session, handle)
    followers = await session.scalar(
        select(func.count()).select_from(Follow).where(Follow.followed_id == user_id)
    )
    following = await session.scalar(
        select(func.count()).select_from(Follow).where(Follow.follower_id == user_id)
    )
    is_following: bool | None = None
    if viewer_id is not None:
        is_following = (
            await session.get(Follow, {"follower_id": viewer_id, "followed_id": user_id})
        ) is not None
    return SocialOut(
        followers=int(followers or 0),
        following=int(following or 0),
        is_following=is_following,
        is_me=viewer_id == user_id,
    )


# --------------------------------------------------- #12 saved


async def saved(
    session: AsyncSession,
    viewer_id: uuid.UUID,
    storage: ObjectStorage,
    *,
    cursor: str | None = None,
    limit: int = _cursor.DEFAULT_PAGE_SIZE,
) -> PostPage:
    """The caller's saves, newest save first. A saved deed the caller may no longer see drops out
    silently (the save row stays, so it comes back if the deed is shown again)."""
    stmt = (
        select(FeedSave.created_at, FeedPost)
        .join(FeedPost, FeedPost.deed_id == FeedSave.deed_id)
        .where(
            FeedSave.user_id == viewer_id,
            or_(
                FeedPost.listed,
                and_(
                    FeedPost.state == PostState.PUBLISHED,
                    or_(FeedPost.doer_id == viewer_id, FeedPost.reporter_id == viewer_id),
                ),
            ),
        )
    )
    if cursor is not None:
        at, last_id = _cursor.decode(cursor)
        stmt = stmt.where(tuple_(FeedSave.created_at, FeedSave.deed_id) < tuple_(at, last_id))
    rows = list(
        (
            await session.execute(
                stmt.order_by(FeedSave.created_at.desc(), FeedSave.deed_id.desc())
                .limit(limit + 1)
                .execution_options(populate_existing=True)
            )
        ).all()
    )
    page, more = rows[:limit], len(rows) > limit
    return PostPage(
        items=await _compose.compose(session, [post for _, post in page], viewer_id, storage),
        next_cursor=_cursor.encode(page[-1][0], page[-1][1].deed_id) if more else None,
    )


# --------------------------------------------------- options (§3.4b #7)


def options(limits: FeedLimits, shared: SharedReportLimits) -> FeedOptions:
    return FeedOptions(
        comment_max_chars=limits.comment_max_chars,
        top_badge_ranks=limits.top_badge_ranks,
        top_periods=[TopPeriodOut(id=p.value, days=limits.top_days(p.value)) for p in TopPeriod],
        comment_report_reasons=[
            ReportReasonOut(id=r.value, label=COMMENT_REPORT_LABELS[r], priority=priority)
            for r, priority in COMMENT_REPORT_PRIORITY.items()
        ],
        report_details_max=shared.report_details_max,
    )
