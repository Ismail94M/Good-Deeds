# Who counts as connected to a person (M6A Q89, ``notifications.network.audience``):
# ``followers`` follow them; ``mutual`` follow them and are followed back;
# ``followers_or_following`` follow them or are followed by them.
Audience = Literal["followers", "mutual", "followers_or_following"]


@dataclass(frozen=True)
class VisibilityView:
    """A post's feed state for the admin page ("Verified · Shown in feed")."""

    state: PostState
    # Shown in the feed and on the public page (published and not hidden by either person).
    listed: bool
    hidden_by_doer_at: datetime | None
    hidden_by_reporter_at: datetime | None


async def is_public(session: AsyncSession, deed_id: uuid.UUID) -> bool:
    """Whether anyone, signed in or not, may see the deed: its post is listed and the deed is
    still verified (live check)."""
    found = await _access.access(session, deed_id, None)
    return found is not None and found.public


async def can_view(session: AsyncSession, deed_id: uuid.UUID, user_id: uuid.UUID) -> bool:
    """Whether ``user_id`` may see the deed: public, or they are its doer or reporter and the post
    is published but hidden."""
    found = await _access.access(session, deed_id, user_id)
    return found is not None and found.viewable


async def visible_deed_ids(
    session: AsyncSession, viewer_id: uuid.UUID, deed_ids: Iterable[uuid.UUID]
) -> set[uuid.UUID]:
    """The deeds among ``deed_ids`` that ``viewer_id`` may see (the ``can_view`` rule), in two
    queries: the posts, then the live deeds."""
    ids = set(deed_ids)
    if not ids:
        return set()
    posts = list(
        await session.scalars(
            select(FeedPost)
            .where(FeedPost.deed_id.in_(ids))
            .execution_options(populate_existing=True)
        )
    )
    live = await deeds.get_deeds(session, [p.deed_id for p in posts])
    visible: set[uuid.UUID] = set()
    for post in posts:
        deed = live.get(post.deed_id)
        if deed is None or deed.status != deeds.DeedStatus.VERIFIED:
            continue
        found = _access.Access(post=post, deed=deed, role=_access.role_of(post, viewer_id))
        if found.viewable:
            visible.add(post.deed_id)
    return visible


async def visibility(session: AsyncSession, deed_id: uuid.UUID) -> VisibilityView | None:
    """The post's stored state, or None if the deed never had a post (never verified)."""
    # populate_existing: ``listed`` is generated by the database, so re-read it.
    post = await session.scalar(
        select(FeedPost)
        .where(FeedPost.deed_id == deed_id)
        .execution_options(populate_existing=True)
    )
    if post is None:
        return None
    return VisibilityView(
        state=post.state,
        listed=post.listed,
        hidden_by_doer_at=post.hidden_by_doer_at,
        hidden_by_reporter_at=post.hidden_by_reporter_at,
    )


@dataclass(frozen=True)
class Follower:
    """One person connected to some of the given people (``follower_ids_page``)."""

    user_id: uuid.UUID
    # Which of the given people they are connected to, sorted.
    of: tuple[uuid.UUID, ...]


async def follower_ids_page(
    session: AsyncSession,
    user_ids: Collection[uuid.UUID],
    *,
    after: uuid.UUID | None,
    limit: int,
    audience: Audience = "followers",
) -> list[Follower]:
    """The people connected to any of ``user_ids`` (by ``audience``), ordered by id, after
    ``after``, at most ``limit``; each once, with the ones they are connected to. The given
    people themselves are left out. A keyset page, so a fan-out can resume after a restart."""
    ids = set(user_ids)
    if not ids or limit < 1:
        return []
    followers = select(Follow.follower_id.label("uid"), Follow.followed_id.label("of")).where(
        Follow.followed_id.in_(ids)
    )
    if audience == "mutual":
        back = Follow.__table__.alias("back")
        followers = followers.join(
            back,
            and_(
                back.c.follower_id == Follow.followed_id,
                back.c.followed_id == Follow.follower_id,
            ),
        )
    source = followers
    if audience == "followers_or_following":
        following = select(Follow.followed_id.label("uid"), Follow.follower_id.label("of")).where(
            Follow.follower_id.in_(ids)
        )
        source = followers.union(following)  # type: ignore[assignment]
    links = source.subquery()
    people = (
        select(links.c.uid)
        .where(links.c.uid.not_in(ids))
        .group_by(links.c.uid)
        .order_by(links.c.uid)
        .limit(limit)
    )
    if after is not None:
        people = people.where(links.c.uid > after)
    page = list(await session.scalars(people))
    if not page:
        return []
    rows = await session.execute(select(links.c.uid, links.c.of).where(links.c.uid.in_(page)))
    of: dict[uuid.UUID, set[uuid.UUID]] = {}
    for uid, target in rows:
        of.setdefault(uid, set()).add(target)
    return [Follower(user_id=uid, of=tuple(sorted(of.get(uid, set())))) for uid in page]


async def earlier_commenter_ids(
    session: AsyncSession,
    deed_id: uuid.UUID,
    *,
    before: uuid.UUID,
    since: datetime,
    exclude: Collection[uuid.UUID] = (),
    limit: int | None = None,
) -> set[uuid.UUID]:
    """Authors of the deed's live (not deleted) comments written at or after ``since`` and
    before the comment ``before`` (M6A D111 "also commented"). The author of ``before`` and
    anyone in ``exclude`` are left out. With ``limit``, at most that many authors, those who
    commented most recently first (SEC6-M1). Empty when ``before`` isn't a comment on this
    deed."""
    new = await session.execute(
        select(FeedComment.created_at, FeedComment.author_id).where(
            FeedComment.id == before, FeedComment.deed_id == deed_id
        )
    )
    found = new.first()
    if found is None:
        return set()
    created_at, author_id = found
    query = (
        select(FeedComment.author_id)
        .where(
            FeedComment.deed_id == deed_id,
            FeedComment.deleted_at.is_(None),
            FeedComment.id != before,
            FeedComment.created_at >= since,
            FeedComment.created_at <= created_at,
            FeedComment.author_id != author_id,
        )
        .group_by(FeedComment.author_id)
        .order_by(func.max(FeedComment.created_at).desc(), FeedComment.author_id)
    )
    if exclude:
        query = query.where(FeedComment.author_id.not_in(list(exclude)))
    if limit is not None:
        query = query.limit(limit)
    return set(await session.scalars(query))
