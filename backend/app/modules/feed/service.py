"""Public interface of the feed module (docs/M3-DESIGN.md §3.4, D30, D36).

Other modules read feed visibility here: ``media/router.py`` (photo reports and the admin review
page). Scoring, points, rewards and leaderboard code must never call these (D30; enforced by
``tests/test_architecture.py``): visibility never reaches verification, counts or prizes.
"""

import uuid
from dataclasses import dataclass
from datetime import datetime

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.modules.feed import _access
from app.modules.feed.models import FeedPost, PostState

__all__ = ["PostState", "VisibilityView", "can_view", "is_public", "visibility"]


@dataclass(frozen=True)
class VisibilityView:
    """A post's feed state for the admin page ("Verified · Shown in feed")."""

    state: PostState
    # Shown in the feed and on the public page (published and not hidden by either person).
    listed: bool
    hidden_by_doer_at: datetime | None
    hidden_by_reporter_at: datetime | None


async def is_public(session: AsyncSession, deed_id: uuid.UUID) -> bool:
    """Whether anyone, signed in or not, may see the deed: its post is listed and the deed is
    still verified (live check)."""
    found = await _access.access(session, deed_id, None)
    return found is not None and found.public


async def can_view(session: AsyncSession, deed_id: uuid.UUID, user_id: uuid.UUID) -> bool:
    """Whether ``user_id`` may see the deed: public, or they are its doer or reporter and the post
    is published but hidden."""
    found = await _access.access(session, deed_id, user_id)
    return found is not None and found.viewable


async def visibility(session: AsyncSession, deed_id: uuid.UUID) -> VisibilityView | None:
    """The post's stored state, or None if the deed never had a post (never verified)."""
    # populate_existing: ``listed`` is generated by the database, so re-read it.
    post = await session.scalar(
        select(FeedPost)
        .where(FeedPost.deed_id == deed_id)
        .execution_options(populate_existing=True)
    )
    if post is None:
        return None
    return VisibilityView(
        state=post.state,
        listed=post.listed,
        hidden_by_doer_at=post.hidden_by_doer_at,
        hidden_by_reporter_at=post.hidden_by_reporter_at,
    )
